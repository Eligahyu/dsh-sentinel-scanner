    '      },',
    '      "devDependencies": { "test-only": "^2.0.0", },',
    '    },',
    '    "packages/tool": {',
    '      "name": "@scope/tool",',
    '      "version": "2.0.0",',
    '      "dependencies": { "beta": "^2.0.0", },',
    '    },',
    '  },',
    '  "packages": {',
    '    "@scope/tool": ["@scope/tool@workspace:packages/tool"],',
    '    "alpha": ["alpha@1.2.0", "", { "dependencies": { "beta": "^1.0.0" } }, "sha512-alpha"],',
    '    "alpha/beta": ["beta@1.1.0", "", {}, "sha512-beta-nested"],',
