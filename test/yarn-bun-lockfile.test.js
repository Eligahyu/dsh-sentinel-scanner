test('yarn classic workspace ranges resolve locally and escape patterns fail', () => {
  const workspaceRoot = tempDir('yarn-classic-workspace')
  const escapeRoot = tempDir('yarn-classic-workspace-escape')
  try {
    mkdirSync(join(workspaceRoot, 'packages', 'tool'), { recursive: true })
    writeJson(join(workspaceRoot, 'package.json'), {
      name: 'workspace-root',
      version: '1.0.0',
      private: true,
      workspaces: ['packages/*'],
      dependencies: { '@scope/tool': '^1.0.0' },
    })
    writeJson(join(workspaceRoot, 'packages', 'tool', 'package.json'), {
      name: '@scope/tool',
      version: '1.2.0',
      dependencies: { alpha: '^1.0.0' },
    })
    writeFileSync(join(workspaceRoot, 'yarn.lock'), [
      'alpha@^1.0.0:',
      '  version "1.2.0"',
      '  integrity sha512-alpha',
      '',
    ].join('\n'))

    const graph = buildDependencyGraph(workspaceRoot)
    assert.equal(graph.complete, true)
    const workspace = graph.nodes.find((node) => node.id === 'workspace:packages/tool')
    assert.ok(workspace)
    assert.equal(workspace.version, '1.2.0')
    assert.equal(workspace.direct, true)
    assert.ok(graph.edges.some((edge) => edge.from === workspace.id
      && edge.to === 'alpha@1.2.0'))

    writeJson(join(escapeRoot, 'package.json'), {
      name: 'escape-root',
      version: '1.0.0',
      workspaces: ['../outside'],
    })
    writeFileSync(join(escapeRoot, 'yarn.lock'), [
      'alpha@^1.0.0:',
      '  version "1.2.0"',
      '',
    ].join('\n'))
    const escape = buildDependencyGraph(escapeRoot)
    assert.equal(escape.complete, false)
    assert.ok(escape.failures.some((failure) => failure.reason === 'workspace-path-error'))
  } finally {
    rmSync(workspaceRoot, { recursive: true, force: true })
    rmSync(escapeRoot, { recursive: true, force: true })
  }
})

