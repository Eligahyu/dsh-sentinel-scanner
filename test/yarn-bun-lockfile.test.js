test('bun.lockb is recognized and explicitly degraded without fabricated nodes', () => {
  const root = tempDir('bun-binary')
  try {
    writeFileSync(join(root, 'bun.lockb'), Buffer.from(
      '#!/usr/bin/env bun\nbun-lockfile-format-v0\n\u0003\u0000\u0000\u0000binary-body',
      'utf8',
    ))

    const graph = buildDependencyGraph(root)

    assert.equal(graph.complete, false)
    assert.equal(graph.ecosystem, 'bun')
    assert.equal(graph.lockfile, 'bun.lockb')
    assert.equal(graph.lockfileVersion, 'v0')
    assert.equal(graph.degraded, true)
    assert.deepEqual(graph.nodes, [])
    assert.deepEqual(graph.edges, [])
    assert.deepEqual(graph.failures, [{
      reason: 'unsupported-binary-lockfile',
      path: 'bun.lockb',
      format: 'bun-lockfile-format-v0',
      detail: 'binary-lockfile-is-recognized-but-not-decoded',
    }])
  } finally {
    rmSync(root, { recursive: true, force: true })
  }
})

test('yarn and bun dependency counts come from the normalized graphs', () => {
  const yarnRoot = tempDir('count-yarn')
  const bunRoot = tempDir('count-bun')
  const bunBinaryRoot = tempDir('count-bun-binary')
  try {
    writeJson(join(yarnRoot, 'package.json'), {
      name: 'count-yarn-root',
      version: '1.0.0',
      dependencies: { alpha: '^1.0.0' },
      devDependencies: { 'test-only': '^2.0.0' },
    })
    writeFileSync(join(yarnRoot, 'yarn.lock'), classicLock())
    assert.deepEqual(countDependencies(yarnRoot, 'yarn.lock'), {
      directDependencies: 2,
      transitiveDependencies: 1,
      dependencyCountComplete: true,
    })

    bunProject(bunRoot)
    assert.deepEqual(countDependencies(bunRoot, 'bun.lock'), {
      directDependencies: 3,
      transitiveDependencies: 2,
      dependencyCountComplete: true,
    })

    writeFileSync(join(bunBinaryRoot, 'bun.lockb'), Buffer.from(
      '#!/usr/bin/env bun\nbun-lockfile-format-v0\nbinary-body',
      'utf8',
    ))
    assert.deepEqual(countDependencies(bunBinaryRoot, 'bun.lockb'), {
      directDependencies: 0,
      transitiveDependencies: 0,
      dependencyCountComplete: false,
      dependencyCountReason: 'unsupported-binary-lockfile',
    })
  } finally {
    rmSync(yarnRoot, { recursive: true, force: true })
    rmSync(bunRoot, { recursive: true, force: true })
    rmSync(bunBinaryRoot, { recursive: true, force: true })
  }
})

test('scan report exposes Yarn build evidence and explicit binary degradation', async () => {
  const yarnRoot = tempDir('report-yarn')
  const binaryRoot = tempDir('report-bun-binary')
  try {
    berryProject(yarnRoot, { hasInstallScript: true })
    const report = await scan(yarnRoot)
    assert.equal(report.analysisLayers.dependencyGraph.ecosystem, 'yarn')
    assert.equal(report.analysisLayers.dependencyGraph.complete, true)
    assert.deepEqual(report.supplyChain.dependencyGraph.buildRequirements, [{
      id: 'alpha@npm:1.2.0',
      name: 'alpha',
      version: '1.2.0',
      evidence: 'yarn-has-install-script',
      dependencyPaths: [['berry-root@1.0.0', 'alpha@1.2.0']],
    }])
    assert.deepEqual(report.supplyChain.dependencyGraph.installScriptEvidence, {
      status: 'observed',
      reason: 'yarn-lockfile-explicit-build-metadata',
    })

    writeFileSync(join(binaryRoot, 'bun.lockb'), Buffer.from(
      '#!/usr/bin/env bun\nbun-lockfile-format-v0\nbinary-body',
      'utf8',
    ))
    const binaryReport = await scan(binaryRoot)
    assert.equal(binaryReport.analysisLayers.dependencyGraph.complete, false)
    assert.equal(binaryReport.supplyChain.dependencyGraph.degraded, true)
    assert.equal(binaryReport.supplyChain.dependencyGraph.failures[0].reason, 'unsupported-binary-lockfile')
  } finally {
    rmSync(yarnRoot, { recursive: true, force: true })
    rmSync(binaryRoot, { recursive: true, force: true })
  }
})
