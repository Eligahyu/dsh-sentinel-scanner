function tempDir(label) {
  return mkdtempSync(join(tmpdir(), `dsh-${label}-`))
}

function writeJson(file, value) {
  writeFileSync(file, JSON.stringify(value))
}

function classicLock() {
  return [
    '# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.',
    '# yarn lockfile v1',
    '',
    'alpha@^1.0.0:',
    '  version "1.2.0"',
    '  resolved "https://registry.yarnpkg.com/alpha/-/alpha-1.2.0.tgz#abc"',
    '  integrity sha512-alpha',
    '  dependencies:',
    '    beta "^1.0.0"',
    '',
    'beta@^1.0.0:',
    '  version "1.4.0"',
    '  resolved "https://registry.yarnpkg.com/beta/-/beta-1.4.0.tgz#def"',
    '  integrity sha512-beta',
    '',
    'test-only@^2.0.0:',
    '  version "2.1.0"',
    '  integrity sha512-test',
    '',
  ].join('\n')
}

function berryLock({ hasInstallScript = false } = {}) {
  return [
    '__metadata:',
    '  version: 8',
    '  cacheKey: 10c0',
    '',
    '"berry-root@workspace:.":',
    '  version: 0.0.0-use.local',
    '  resolution: "berry-root@workspace:."',
    '  dependencies:',
    '    "@scope/tool": "workspace:*"',
    '    alpha: "npm:^1.0.0"',
    '    test-only: "npm:^2.0.0"',
    '  languageName: unknown',
    '  linkType: soft',
    '',
    '"@scope/tool@workspace:*, @scope/tool@workspace:packages/tool":',
    '  version: 0.0.0-use.local',
    '  resolution: "@scope/tool@workspace:packages/tool"',
    '  dependencies:',
    '    beta: "npm:^2.0.0"',
    '  languageName: unknown',
    '  linkType: soft',
    '',
    '"alpha@npm:^1.0.0":',
    '  version: 1.2.0',
    '  resolution: "alpha@npm:1.2.0"',
    '  dependencies:',
    '    beta: "npm:^2.0.0"',
    '  checksum: 10c0/alpha',
    ...(hasInstallScript ? ['  hasInstallScript: true'] : []),
    '  languageName: node',
    '  linkType: hard',
    '',
    '"beta@npm:^2.0.0":',
    '  version: 2.0.0',
    '  resolution: "beta@npm:2.0.0"',
    '  checksum: 10c0/beta',
    '  languageName: node',
    '  linkType: hard',
    '',
    '"test-only@npm:^2.0.0":',
    '  version: 2.1.0',
    '  resolution: "test-only@npm:2.1.0"',
    '  checksum: 10c0/test',
    '  languageName: node',
    '  linkType: hard',
    '',
  ].join('\n')
}

function berryProject(root, options = {}) {
  mkdirSync(join(root, 'packages', 'tool'), { recursive: true })
  writeJson(join(root, 'package.json'), {
    name: 'berry-root',
    version: '1.0.0',
    private: true,
    workspaces: ['packages/*'],
    dependencies: { alpha: '^1.0.0', '@scope/tool': 'workspace:*' },
    devDependencies: { 'test-only': '^2.0.0' },
  })
  writeJson(join(root, 'packages', 'tool', 'package.json'), {
    name: '@scope/tool',
    version: '2.0.0',
    dependencies: { beta: '^2.0.0' },
  })
  writeFileSync(join(root, 'yarn.lock'), berryLock(options))
}

