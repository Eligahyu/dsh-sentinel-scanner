test('yarn classic graph normalizes direct/transitive nodes and dependency chains', () => {
  const root = tempDir('yarn-classic')
  try {
    writeJson(join(root, 'package.json'), {
      name: 'classic-root',
      version: '1.0.0',
      dependencies: { alpha: '^1.0.0' },
      devDependencies: { 'test-only': '^2.0.0' },
    })
    writeFileSync(join(root, 'yarn.lock'), classicLock())

    const graph = buildDependencyGraph(root)

    assert.equal(graph.complete, true)
    assert.equal(graph.ecosystem, 'yarn')
    assert.equal(graph.lockfile, 'yarn.lock')
    assert.equal(graph.lockfileVersion, '1')
    assert.deepEqual(graph.nodes.map((node) => [node.name, node.version, node.direct, node.dev]), [
      ['alpha', '1.2.0', true, false],
      ['beta', '1.4.0', false, false],
      ['test-only', '2.1.0', true, true],
    ])
    assert.deepEqual(graph.edges, [{
      from: 'alpha@1.2.0',
      to: 'beta@1.4.0',
      name: 'beta',
      kind: 'runtime',
    }])
    assert.equal(graph.root.directDependencies, 2)
    assert.deepEqual(graph.failures, [])
    assert.deepEqual(graph.buildRequirements, [])
    assert.equal(graph.installScriptEvidence.status, 'unavailable')
    assert.deepEqual(dependencyPaths(graph, 'beta'), [[
      'classic-root@1.0.0',
      'alpha@1.2.0',
      'beta@1.4.0',
    ]])
  } finally {
    rmSync(root, { recursive: true, force: true })
  }
})

